"""fx_registry.py - the list of person-aware effects, and the small helpers every effect uses to read its options.

An effect is a function `fn(c, e)`: `c` is the frame (fx_core.Ctx), `e` the effect instance with its window and options. It is registered with
`@effect(name, description, opts=...)`; the metadata is what `person_fx.py list`, the plan linter, the audit and data/effects.json read.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field

from fx_core import rgb

EFFECTS: dict = {}
ALIASES: dict = {}


@dataclass
class Effect:
    name: str
    fn: object
    desc: str
    opts: dict = field(default_factory=dict)     # option name -> what it does
    family: str = "light"                        # type | light | camera | cards | ui | data | glass | frame
    depth: str = "mixed"                         # behind | front | guard | mixed | none: where it draws relative to the person
    matte: bool = False                          # needs a real person matte to look right (a rough one only places things around the person)
    cover_ok: bool = False                       # may legitimately cover the head (a grade, a full-frame treatment)
    images: bool = False                         # takes an `images` folder (reels, covers, b-roll stills); falls back to frames of the video
    camera: bool = False                         # moves or warps the whole frame: runs before the others
    seconds: tuple = (1.5, 4.0)                  # the window length that looks best
    intents: tuple = ()                          # story jobs it serves (ids from data/intents.json) or generic tags
    looks: dict = field(default_factory=dict)    # named variants: look value -> what changes


def effect(name, desc, opts=None, *, family="light", depth="mixed", matte=False, cover_ok=False, images=False, camera=False,
           seconds=(1.5, 4.0), intents=(), looks=None, aliases=()):
    def deco(fn):
        EFFECTS[name] = Effect(name, fn, desc, dict(opts or {}), family, depth, matte, cover_ok, images, camera, tuple(seconds), tuple(intents), dict(looks or {}))
        for a in aliases:
            ALIASES[a] = name
        return fn
    return deco


class Fx:
    """One effect scheduled in a plan: a window and its options."""

    def __init__(self, d: dict):
        self.name = d["fx"]
        self.start = float(d["start"])
        self.end = float(d["end"])
        self.d = max(0.05, self.end - self.start)
        self.o = {k: v for k, v in d.items() if k not in ("fx", "start", "end", "on", "until", "lead", "after", "dur", "note")}
        self.state: dict = {}
        self.cards: list = []


# ------------------------------------------------------------------------------------------------------------- option readers

def opt(e, key, default=None):
    v = e.o.get(key)
    return default if v is None or v == "" else v


def num(e, key, default):
    try:
        return float(e.o[key]) if e.o.get(key) not in (None, "") else float(default)
    except (TypeError, ValueError):
        return float(default)


def txt(e, key, default=""):
    v = e.o.get(key)
    return str(default if v is None or v == "" else v)


def lst(e, key, default=()):
    """A list option: a JSON list, or a string with items separated by |."""
    v = e.o.get(key)
    if v is None or v == "":
        return list(default)
    if isinstance(v, (list, tuple)):
        return [str(x) for x in v]
    return [s.strip() for s in str(v).split("|") if s.strip()]


def col(e, key, default):
    return rgb(e.o.get(key), default)


def times(e, key="ticks"):
    """Video-time seconds listed in an option (a list or a | string), converted to seconds into the effect."""
    out = []
    for s in lst(e, key):
        try:
            out.append(float(s) - e.start)
        except ValueError:
            pass
    return out


def catalog() -> dict:
    """The registry as plain data (what data/effects.json holds)."""
    out = {}
    for n, x in sorted(EFFECTS.items()):
        out[n] = {"description": x.desc, "family": x.family, "depth": x.depth, "needs_matte": x.matte, "may_cover_head": x.cover_ok, "takes_images": x.images,
                  "moves_camera": x.camera, "best_seconds": list(x.seconds), "options": x.opts, "looks": x.looks, "serves": list(x.intents),
                  "aliases": sorted(a for a, t in ALIASES.items() if t == n)}
    return out


def dump_catalog(path=None) -> str:
    s = json.dumps({"_comment": "Generated by person_fx.py catalog --write from the effect registry. Do not edit by hand: tests check it is current.",
                    "effects": catalog()}, indent=1, ensure_ascii=False) + "\n"
    if path:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(s)
    return s
